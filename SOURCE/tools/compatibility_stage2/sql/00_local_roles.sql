-- CANDIDATE RESEARCH ONLY. Fresh disposable PostgreSQL database only.
-- No Supabase migration, password, production identity or remote connection.
\set ON_ERROR_STOP on
DO $$
BEGIN
  IF current_database() <> 'zyra_compat_stage2_research' THEN
    RAISE EXCEPTION 'wrong sandbox database';
  END IF;
  IF EXISTS (SELECT 1 FROM pg_namespace WHERE nspname IN ('s2_private','s2_api','s2_fixture')) THEN
    RAISE EXCEPTION 'sandbox schemas already exist; refuse implicit replay';
  END IF;
END $$;
CREATE ROLE s2_owner NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
CREATE ROLE s2_maintenance NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
CREATE ROLE s2_authenticated NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
CREATE ROLE s2_viewer LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
CREATE ROLE s2_viewer2 LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
CREATE ROLE s2_target LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
CREATE ROLE s2_target2 LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
CREATE ROLE s2_other LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
CREATE ROLE s2_demo LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
CREATE ROLE s2_guardian LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
CREATE ROLE s2_anon LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
GRANT s2_authenticated TO s2_viewer,s2_viewer2,s2_target,s2_target2,s2_other,s2_demo,s2_guardian;
REVOKE ALL ON DATABASE zyra_compat_stage2_research FROM PUBLIC;
GRANT CONNECT ON DATABASE zyra_compat_stage2_research TO s2_authenticated,s2_anon;
REVOKE ALL ON SCHEMA public FROM PUBLIC;
CREATE SCHEMA s2_private AUTHORIZATION s2_owner;
CREATE SCHEMA s2_api AUTHORIZATION s2_owner;
CREATE SCHEMA s2_fixture;
REVOKE ALL ON SCHEMA s2_private,s2_api,s2_fixture FROM PUBLIC;
GRANT USAGE ON SCHEMA s2_api TO s2_authenticated,s2_anon;
ALTER DEFAULT PRIVILEGES FOR ROLE s2_owner IN SCHEMA s2_private,s2_api
  REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;
ALTER DEFAULT PRIVILEGES IN SCHEMA s2_fixture REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;
SET ROLE s2_owner;
CREATE TABLE s2_private.sandbox_identity (
  id integer PRIMARY KEY CHECK(id=1),
  marker text NOT NULL CHECK(marker='compatibility-stage2-synthetic-only'),
  database_name text NOT NULL CHECK(database_name='zyra_compat_stage2_research')
);
INSERT INTO s2_private.sandbox_identity VALUES(1,'compatibility-stage2-synthetic-only',current_database());
RESET ROLE;
